def install_functions(namespace: MutableMapping[str, Any]) -> None:
    modules = {
        module_name: importlib.import_module(f".{module_name}", __package__)
        for module_name in sorted(set(_METHOD_MODULES.values()))
    }
    for name, module_name in _METHOD_MODULES.items():
        module = modules[module_name]
        implementation = module.implementation(name)
        if implementation is None:
            raise AttributeError(name)

        def make_wrapper(function_name, service_module, wrapped):
            @wraps(wrapped)
            def wrapper(*args, **kwargs):
                return service_module.invoke(function_name, *args, **kwargs)
            return wrapper

        namespace[name] = make_wrapper(name, module, implementation)
