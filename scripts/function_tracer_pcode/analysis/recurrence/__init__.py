def resolve_method(name: str) -> Optional[Callable[..., Any]]:
    module_name = _METHOD_MODULES.get(name)
    if module_name is None:
        return None
    module = importlib.import_module(f".{module_name}", __package__)
    implementation = module.implementation(name)
    if implementation is None:
        raise AttributeError(name)

    @wraps(implementation)
    def delegated(*args: Any, **kwargs: Any) -> Any:
        return module.invoke(name, *args, **kwargs)

    return delegated
